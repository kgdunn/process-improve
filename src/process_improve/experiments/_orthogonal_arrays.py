#: Names of the stored arrays, in order of run count.
ORTHOGONAL_ARRAY_NAMES: tuple[str, ...] = tuple(_ARRAYS)


@functools.cache
def orthogonal_array(name: str) -> np.ndarray:
    """Return a stored orthogonal array by name.

    Parameters
    ----------
    name : str
        One of :data:`ORTHOGONAL_ARRAY_NAMES`, such as ``"L8(2^7)"``.

    Returns
    -------
    np.ndarray
        Integer array of zero-based levels, one row per run and one column per factor.
        It is cached and shared between callers, so it is read-only.

    Raises
    ------
    ValueError
        If ``name`` is not a stored array.
    """
    if name not in _ARRAYS:
        raise ValueError(f"Unknown orthogonal array {name!r}; available: {', '.join(_ARRAYS)}")
    array = np.array([[int(level) for level in row] for row in _ARRAYS[name].split()])
    array.flags.writeable = False
    return array
